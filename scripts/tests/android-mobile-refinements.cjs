const assert = require('node:assert/strict')
const path = require('node:path')
module.exports = async (ui, output) => {
  const {run, waitFor, tap, adb, delay, screenshot} = ui
  const shot = async name => { await delay(200); await screenshot(path.join(output,name+'.png')) }
  const back = async () => { await ui.dismissKeyboard(); adb(['shell','input','keyevent','4']); await delay(150) }
  const textButton = async (text, root) => {
    await run(`(()=>{document.querySelectorAll('[data-refinement-action]').forEach(e=>e.removeAttribute('data-refinement-action'));const e=[...document.querySelector(${JSON.stringify(root)}).querySelectorAll('button')].find(e=>e.textContent.trim()===${JSON.stringify(text)});if(!e)throw Error('Missing action '+${JSON.stringify(text)});e.dataset.refinementAction='true'})()`)
    await tap('[data-refinement-action=true]')
  }
  await ui.navigate('Conversation')
  assert.equal(await run('Boolean(document.querySelector(".mobile-conversation-header .lucide-panels-top-left"))'),true,'workspace icon depicts panels')
  assert.equal(await run('getComputedStyle(document.querySelector(".mobile-conversation-header")).backgroundColor!==getComputedStyle(document.querySelector(".chat-panel")).backgroundColor'),true,'header has a distinct filled surface')
  await tap('button[aria-label="Chat tools"]')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools"))')
  assert.equal(await run('Boolean(document.querySelector(".message-box__selectors [aria-label=\\"Set goal\\"]"))'),false,'extras leave the model selector its full row')
  await shot('chat-tools')
  await tap('.mobile-chat-tools [aria-label="Set goal"]')
  await waitFor('Boolean(document.querySelector("dialog.chat-goal-dialog[open]"))')
  await back()
  await waitFor('!document.querySelector("dialog.chat-goal-dialog[open]")')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools"))')
  await tap('.mobile-chat-tools .cwd-notes button')
  await waitFor('Boolean(document.querySelector(".cwd-notes-menu"))')
  await back()
  await waitFor('!document.querySelector(".cwd-notes-menu")')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools"))')
  await tap('.mobile-chat-tools .cwd-actions button')
  await waitFor('Boolean(document.querySelector(".cwd-actions-dialog"))')
  await back()
  await waitFor('!document.querySelector(".cwd-actions-dialog")')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools"))')
  await tap('.mobile-chat-tools [aria-label="Limits and usage"]')
  await waitFor('Boolean(document.querySelector(\'[role=dialog][aria-label="Usage"]\'))')
  await back()
  await waitFor('!document.querySelector(\'[role=dialog][aria-label="Usage"]\')')
  await tap('.mobile-chat-tools [aria-label="On Limit Reset"]')
  await waitFor('Boolean(document.querySelector("dialog.chat-goal-dialog[open]"))')
  await back()
  await waitFor('!document.querySelector("dialog.chat-goal-dialog[open]")')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools"))')
  await back()
  await waitFor('!document.querySelector(".mobile-chat-tools")')

  await ui.navigate('Chats')
  await tap('.mobile-sidebar-footer__actions [aria-label="New chat"]')
  await ui.dismissKeyboard()
  await waitFor('Boolean(document.querySelector(".mobile-session-setup"))')
  assert.ok(await run('document.querySelector(".chat-panel__new-chat-vegvisir").getBoundingClientRect().width>=innerWidth*.65'),'new chat symbol fills a useful portion of the phone')
  assert.ok(await run('document.querySelector(".message-box__chat-config-trigger").getBoundingClientRect().width>=innerWidth*.85'),'model selection has room')
  assert.ok(await run('(()=>{const e=document.querySelector(".message-box__chat-config-trigger .message-box__chat-config-label-part");return e.scrollWidth<=e.clientWidth+1})()'),'long selected model label is readable without horizontal clipping')
  await shot('new-chat')
  await tap('[aria-label="Chat setup"]')
  await waitFor('Boolean(document.querySelector(".mobile-session-fields"))')
  await shot('chat-setup')
  const labels = await run('[...document.querySelectorAll(".mobile-session-fields [role=combobox]")].map(e=>e.getAttribute("aria-label"))')
  assert.ok(labels.includes('Project')&&labels.includes('Provider')&&labels.includes('Session location')&&labels.includes('Runtime'))
  for (const label of labels) {
    console.log("ANDROID SETUP:",label)
    if(await run(`document.querySelector('.mobile-session-fields [aria-label=${JSON.stringify(label)}]').disabled`))continue
    await tap(`.mobile-session-fields [aria-label=${JSON.stringify(label)}]`)
    await waitFor('Boolean(document.querySelector("[role=listbox]"))')
    if (label === 'Project') {
      const deadline=Date.now()+10000
      while(Date.now()<deadline&&!ui.keyboardVisible())await delay(100)
      assert.equal(ui.keyboardVisible(),true,'project search keeps its native keyboard')
      await waitFor('Boolean(document.querySelector("[role=listbox]"))')
    }
    assert.ok(await run('(()=>{const r=document.querySelector("[role=listbox]").getBoundingClientRect();return r.left>=-1&&r.right<=innerWidth+1&&r.top>=-1&&r.bottom<=innerHeight+1})()'),'setup options fit '+label)
    await back()
    await waitFor('!document.querySelector("[role=listbox]")')
    await waitFor('Boolean(document.querySelector(".mobile-session-fields"))')
  }
  await back()
  await waitFor('!document.querySelector(".mobile-session-fields")')
  await tap('.message-box__chat-config-trigger')
  await waitFor('Boolean(document.querySelector(".message-box__chat-config-menu"))')
  assert.equal(await run('Boolean(document.querySelector(".message-box__chat-config-columns"))'),false,'phone configuration is a vertical menu')
  await tap('button[data-chat-config-section=model]')
  await waitFor('Boolean(document.querySelector(".message-box__chat-config-search"))')
  await back()
  await waitFor('!document.querySelector(".message-box__chat-config-menu")')
  await tap('.message-box__chat-config-trigger')
  await textButton('Save preset','.message-box__chat-config-menu')
  await waitFor('Boolean(document.querySelector(".message-box__chat-config-preset-row"))')
  assert.equal(await run('(()=>{const r=document.querySelector(".message-box__chat-config-preset-row").getBoundingClientRect();return r.left>=-1&&r.right<=innerWidth+1})()'),true,'preset fits phone width')
  assert.ok(await run('(()=>{const e=document.querySelector(".message-box__chat-config-preset .message-box__chat-config-label-part");return e.scrollWidth<=e.clientWidth+1})()'),'long saved preset label wraps without clipping')
  assert.ok(await run('document.querySelector(\'.message-box__chat-config-preset-actions button\').getBoundingClientRect().height>=39'), 'preset actions remain usable touch targets')
  await shot('model-presets')
  await textButton('Configure','.message-box__chat-config-menu')
  await waitFor('Boolean(document.querySelector("button[data-chat-config-section=model]"))')
  await back()
  await waitFor('!document.querySelector(".message-box__chat-config-menu")')

  await ui.navigate('Workspace')
  await tap('.changes-sidebar [aria-label="Sidebar view"] [aria-label=Git]')
  await tap('.changes-sidebar [aria-label="Git view"] [aria-label="Pull requests"]')
  await waitFor('Boolean(document.querySelector(".changes-sidebar__pull-request-search"))')
  assert.ok(await run('document.querySelector(\'[aria-label="Search pull requests"]\').getBoundingClientRect().width>=innerWidth*.7'),'pull request search uses its full row')
  await shot('pull-request-search')
  await waitFor('Boolean(document.querySelector(\'button[aria-label^="View pull request #123:"]\'))')
  await tap('button[aria-label^="View pull request #123:"]')
  await waitFor('Boolean(document.querySelector(".changes-sidebar__pull-request-detail"))')
  await back()
  await waitFor('!document.querySelector(".changes-sidebar__pull-request-detail")')
  await waitFor('Boolean(document.querySelector(".changes-sidebar__pull-request-search"))')
  await back()
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="conversation"')
  await ui.navigate('Conversation')
  await back()
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="chats"')
  await ui.touchPoint(await run('(()=>{const r=document.getElementById("sidebar").getBoundingClientRect();return {x:(r.right+innerWidth)/2,y:innerHeight/2}})()'))
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="conversation"')
  assert.equal(await run('Boolean(document.querySelector(".chat-panel--new, .chat-panel--selected"))'),true,'closing the root chat list preserves the conversation or draft')
  await back()
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="chats"')
  await tap('[data-chat-id="lan-fixture"] .chat-list-item__main')
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="conversation"')
  console.log('ANDROID REFINEMENTS PASSED: chat tools and nested Back, setup selectors, large symbol, fitting presets, PR search/detail Back, workspace/chats Back, filled toolbar')
}
