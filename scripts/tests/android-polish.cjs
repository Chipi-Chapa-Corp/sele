const assert = require('node:assert/strict')
const path = require('node:path')
module.exports = async (ui, output) => {
  const {run, tap, waitFor, adb, delay} = ui
  const back = async () => { adb(['shell','input','keyevent','4']); await delay(600) }
  const textButton = async text => {
    await run(`(()=>{document.querySelectorAll('[data-polish-action]').forEach(e=>e.removeAttribute('data-polish-action'));const e=[...document.querySelectorAll('.message-box__chat-config-menu button')].find(e=>e.textContent.trim()===${JSON.stringify(text)});if(!e)throw Error('Missing '+${JSON.stringify(text)});e.dataset.polishAction='true'})()`)
    await tap('[data-polish-action]')
  }
  if (!process.env.SELE_ANDROID_POLISH_PLACEHOLDER_ONLY) {
  assert.equal(ui.keyboardVisible(), false, 'opening a conversation never opens the keyboard')
  await tap('.chat-panel__composer textarea')
  const keyboardEnd=Date.now()+10000
  while(Date.now()<keyboardEnd&&!ui.keyboardVisible())await delay(100)
  assert.equal(ui.keyboardVisible(), true, 'explicit composer tap opens keyboard')
  adb(['shell','input','text','Draft'])
  await back()
  assert.equal(ui.keyboardVisible(), false)
  assert.equal(await run('document.querySelector("main.chat").dataset.mobilePane'), 'conversation', 'keyboard Back stays in conversation')
  await back()
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="chats"')
  const gap=await run('(()=>{const title=document.querySelector(".chat-list-group__toggle-content--project .chat-list-group__title"),icon=document.querySelector(".chat-list-group__project-icon-button");return title&&icon?title.getBoundingClientRect().left-icon.getBoundingClientRect().right:null})()')
  assert.ok(gap>=6,'project icon and title have breathing room')
  const row='[data-chat-id="lan-fixture"]'
  await run(`(()=>{window.__polishDrags=0;document.querySelector(${JSON.stringify(row)}).addEventListener('dragstart',()=>window.__polishDrags++)})()`)
  assert.equal(await run(`document.querySelector(${JSON.stringify(row)}).draggable`),false)
  await ui.hold(row+' .chat-list-item__main')
  await waitFor(`document.querySelector(${JSON.stringify(row)})?.dataset.touchActions==="open"`)
  assert.equal(await run(`document.querySelector(${JSON.stringify(row)}).draggable`),false,'first hold reveals buttons without arming drag')
  assert.equal(await run('window.__polishDrags'),0)
  await ui.hold(row+' .chat-list-item__main')
  assert.equal(await run(`document.querySelector(${JSON.stringify(row)}).draggable`),true,'a new gesture on the revealed row can drag')
  await ui.screenshot(path.join(output,'held-chat.png'))
  await ui.navigate('Conversation')
  await tap('button[aria-label="Chat tools"]')
  await tap('.mobile-chat-tools [aria-label="Set goal"]')
  await waitFor('Boolean(document.querySelector("dialog.chat-goal-dialog[open]"))')
  await delay(500)
  assert.equal(ui.keyboardVisible(),false,'goal dialog does not autofocus')
  assert.equal(await run('document.activeElement?.matches("input,textarea,[contenteditable=true]")'), false)
  await back()
  await waitFor('!document.querySelector("dialog.chat-goal-dialog[open]")')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools"))')
  await back()
  await waitFor('!document.querySelector(".mobile-chat-tools")')
  await tap('.message-box__chat-config-trigger')
  await waitFor('Boolean(document.querySelector(".message-box__chat-config-menu"))')
  if(await run('Boolean(document.querySelector(".message-box__chat-config-preset-row"))'))await textButton('Configure')
  await textButton('Save preset')
  await waitFor('Boolean(document.querySelector(".message-box__chat-config-preset-row"))')
  const preset=await run('(()=>{const row=document.querySelector(".message-box__chat-config-preset-row"),option=row.querySelector(".message-box__chat-config-preset"),actions=row.querySelector(".message-box__chat-config-preset-actions");const r=option.getBoundingClientRect(),a=actions.getBoundingClientRect();return {r:r.toJSON(),a:a.toJSON(),checks:row.querySelectorAll(".message-box__chat-config-check").length,background:getComputedStyle(row).backgroundColor}})()')
  assert.ok(Math.abs(preset.r.y+preset.r.height/2-preset.a.y-preset.a.height/2)<2,'preset label and actions are centered on one row')
  assert.ok(preset.a.x>=preset.r.right-1,'preset actions are right of label')
  assert.equal(preset.checks,0,'mobile selected preset has no tick')
  assert.notEqual(preset.background,'rgba(0, 0, 0, 0)','selected preset uses active background')
  await ui.screenshot(path.join(output,'preset-inline.png'))
  await tap('.message-box__chat-config-preset-actions button[aria-label^="Edit preset:"]')
  await waitFor('Boolean(document.querySelector("button[data-chat-config-section=model]"))')
  assert.equal(ui.keyboardVisible(),false)
  await back()
  await waitFor('!document.querySelector(".message-box__chat-config-menu")')
  assert.equal(await run('document.querySelector("main.chat").dataset.mobilePane'),'conversation')
  await tap('.message-box__chat-config-trigger')
  await textButton('Configure')
  await tap('button[data-chat-config-section=model]')
  await waitFor('Boolean(document.querySelector(".message-box__chat-config-search input"))')
  const searchEnd=Date.now()+10000
  while(Date.now()<searchEnd&&!ui.keyboardVisible())await delay(100)
  assert.equal(ui.keyboardVisible(),true,'model search may autofocus')
  await back()
  if(await run('Boolean(document.querySelector(".message-box__chat-config-menu"))'))await back()
  await waitFor('!document.querySelector(".message-box__chat-config-menu")')
  assert.equal(await run('document.querySelector("main.chat").dataset.mobilePane'),'conversation')
  }
  const working=await run('(()=>{const phrase=document.querySelector(".chat-detail__working-phrase"),elapsed=document.querySelector(".chat-detail__working-elapsed");return {phrase:phrase?.getBoundingClientRect().toJSON(),elapsed:elapsed?.getBoundingClientRect().toJSON(),text:elapsed?.innerText,html:phrase?.parentElement.outerHTML}})()')
  console.log('WORKING PLACEHOLDER:',JSON.stringify(working))
  if(!working.phrase) console.log('WORKING DIAGNOSTIC:',await run('(async()=>JSON.stringify({chat:document.querySelector(".chat-list-item--selected")?.dataset.chatId,body:document.getElementById("chat-search-content")?.innerText,detail:await providerApi.getChat("codex","lan-fixture")}))()'))
  assert.ok(working.phrase && working.elapsed,'working time and phrase exist')
  assert.ok(working.elapsed.y>=working.phrase.bottom-1,'time and price are below the placeholder')
  assert.match(working.text,/·\s*0\.12\$/)
  assert.ok(!working.text.trim().startsWith('·'),'elapsed row has no leading dot')
  await ui.screenshot(path.join(output,'working-placeholder.png'))
  console.log('ANDROID POLISH PASSED: no ordinary autofocus, IME Back, overlay Back, inline preset actions, search autofocus, two-stage chat drag, stacked working cost')
}
