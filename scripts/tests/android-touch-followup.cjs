const assert = require('node:assert/strict')
const path = require('node:path')
module.exports = async (ui, output) => {
  const {run, tap, waitFor, adb, delay} = ui
  const type = value => adb(['shell','input','text',"'"+value.replace(/ /g,'%s').replace(/'/g,"'\"'\"'")+"'"])
  const clear = async () => { adb(['shell','input','keycombination','113','29']); adb(['shell','input','keyevent','67']); await delay(100) }
  await ui.navigate('Conversation')
  assert.equal(await run(`(()=>{const h=getComputedStyle(document.querySelector('.mobile-conversation-header')).backgroundColor;const c=getComputedStyle(document.querySelector('main.chat')).backgroundColor;const b=getComputedStyle(document.body).backgroundColor;return h===(c==='rgba(0, 0, 0, 0)'?b:c)})()`), true,'toolbar uses the shell surface')
  await tap('#message-input')
  type('$native')
  await waitFor(`Boolean(document.querySelector('[role=listbox][aria-label="Skills and apps"] [role=option]'))`)
  assert.equal(ui.keyboardVisible(),true)
  await tap('[role=listbox][aria-label="Skills and apps"] [role=option]')
  await waitFor(`Boolean(document.querySelector('button[aria-label="Remove native-skill skill"]'))`)
  assert.equal(ui.keyboardVisible(),true,'one skill tap selects while retaining IME')
  await tap('button[aria-label="Remove native-skill skill"]')
  console.log('ANDROID IME: skill selected with one tap')
  await tap('#message-input')
  type('@READ')
  await waitFor(`Boolean(document.querySelector('[role=listbox][aria-label="Files"] [role=option]'))`)
  await tap('[role=listbox][aria-label="Files"] [role=option]')
  await waitFor(`Boolean(document.querySelector('button[aria-label="Remove README.md"]'))`)
  assert.equal(ui.keyboardVisible(),true,'one file tap selects while retaining IME')
  await tap('button[aria-label="Remove README.md"]')
  console.log('ANDROID IME: file selected with one tap')
  await tap('#message-input')
  type('#A')
  await waitFor(`Boolean(document.querySelector('[role=listbox][aria-label="Projects"] [role=option]'))`)
  await tap('[role=listbox][aria-label="Projects"] [role=option]')
  await waitFor('document.querySelector("#message-input").value.includes("/fixture")')
  assert.equal(ui.keyboardVisible(),true,'one project tap inserts its path while retaining IME')
  assert.equal(await run('getComputedStyle(document.activeElement).outlineStyle'), 'none', 'editing never adds a phone focus outline')
  await clear()
  await ui.dismissKeyboard()
  await run(`(()=>{const f=document.createElement('form');f.id='native-submit-proof';f.style.cssText='position:fixed;z-index:9000;left:20px;right:20px;top:100px;padding:20px;background:var(--bg)';f.innerHTML='<input aria-label="Native form input"><button type="submit">Submit once</button>';window.__nativeSubmits=0;f.onsubmit=e=>{e.preventDefault();window.__nativeSubmits++};document.body.append(f)})()`)
  await tap('#native-submit-proof input')
  type('native input')
  assert.equal(ui.keyboardVisible(),true)
  await tap('#native-submit-proof button')
  await waitFor('window.__nativeSubmits===1')
  await delay(200)
  assert.equal(await run('window.__nativeSubmits'),1,'native form submits once on the first touch with IME open')
  await run('document.getElementById("native-submit-proof").remove()')
  await ui.dismissKeyboard()
  await tap('button[aria-label="Chat tools"]')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools"))')
  await tap('.mobile-chat-tools .cwd-actions button[aria-label="Create action"]')
  await waitFor('Boolean(document.querySelector(".cwd-actions-dialog"))')
  await tap('.cwd-actions-dialog__name-row input')
  type('Mobile alignment proof')
  await tap('.cwd-actions-dialog__command')
  type('echo mobile-fixture')
  await tap('.cwd-actions-dialog__footer .ui-button--primary')
  await waitFor('!document.querySelector(".cwd-actions-dialog")')
  await ui.dismissKeyboard()
  if(!await run('Boolean(document.querySelector(".mobile-chat-tools"))'))await tap('button[aria-label="Chat tools"]')
  await waitFor('Boolean(document.querySelector(".mobile-chat-tools .cwd-actions .ui-button--split-toggle"))')
  const geometry=await run(`(()=>{const q=s=>document.querySelector(s)?.getBoundingClientRect();const reset=q('.mobile-chat-tools [aria-label="On Limit Reset"]');const notes=q('.mobile-chat-tools .cwd-notes button');return {resetLeft:reset?.left,notesLeft:notes?.left,icons:[...document.querySelectorAll('.mobile-chat-tools .ui-button--icon-only')].map(e=>{const b=e.getBoundingClientRect(),i=e.querySelector('.ui-button__icon')?.getBoundingClientRect();return {width:b.width,height:b.height,dx:i?i.x+i.width/2-b.x-b.width/2:0,dy:i?i.y+i.height/2-b.y-b.height/2:0}})}})()`)
  assert.ok(Math.abs(geometry.resetLeft-geometry.notesLeft)<=1,'On reset aligns with the other chat tool rows')
  for(const icon of geometry.icons){assert.ok(Math.abs(icon.width-icon.height)<=1,'tool icon button is square');assert.ok(Math.abs(icon.dx)<=1&&Math.abs(icon.dy)<=1,'tool icon is centered')}
  await ui.screenshot(path.join(output,'chat-tools-aligned.png'))
  adb(['shell','input','keyevent','4'])
  await waitFor('!document.querySelector(".mobile-chat-tools")')
  const actions=await run('[...document.querySelectorAll(".chat-detail__message-actions .ui-button")].map(e=>{const r=e.getBoundingClientRect();return {width:r.width,height:r.height}})')
  assert.ok(actions.length>0)
  for(const r of actions)assert.ok(Math.abs(r.width-r.height)<=1,'message action icons use square buttons')
  await ui.navigate('Workspace')
  for(let i=0;i<10;i++)await tap(`.changes-sidebar [aria-label="Sidebar view"] button[aria-label="${i%2?'Files':'Git'}"]`)
  adb(['shell','input','keyevent','4'])
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="conversation"')
  await ui.navigate('Workspace')
  const box=await run('(()=>{const r=document.querySelector(".changes-sidebar__body").getBoundingClientRect();return {x:r.x,width:r.width,y:r.y+Math.min(180,r.height*.4)}})()')
  await ui.swipe({x:box.x+box.width*.2,y:box.y},{x:box.x+box.width*.8,y:box.y})
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="chats"')
  assert.ok(await run('parseFloat(getComputedStyle(document.getElementById("sidebar")).borderTopRightRadius)>0'),'drawer edge is rounded')
  adb(['shell','input','keyevent','4'])
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="workspace"')
  adb(['shell','input','keyevent','4'])
  await waitFor('document.querySelector("main.chat").dataset.mobilePane==="conversation"')
  console.log('ANDROID TOUCH FOLLOWUP PASSED: IME first-tap skill/file/project selection and form submit, no focus outline, centered square controls, section Back, workspace drawer swipe')
}
