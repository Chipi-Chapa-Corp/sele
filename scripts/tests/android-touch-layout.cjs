const assert = require('node:assert/strict')
const path = require('node:path')

module.exports = async (ui, output) => {
  const { run, waitFor, tap, hold, swipe, adb, screenshot, delay } = ui
  const nav = ui.navigate
  const pane = (value) => waitFor(`document.querySelector('main.chat')?.dataset.mobilePane===${JSON.stringify(value)}`)
  const row = '[data-chat-id="lan-fixture"]'
  const actionsVisible = `getComputedStyle(document.querySelector('${row} .chat-list-item__actions')).display!=='none'`
  const shot = (name) => screenshot(path.join(output, name + '.png'))
  const horizontal = async (direction) => {
    const { width, top, height } = await run('(()=>{const r=document.querySelector(".chat__panels").getBoundingClientRect();return {width:r.width,top:r.top,height:r.height}})()')
    const y = top + Math.min(200, height * 0.4)
    await swipe({ x: width * (direction === 'next' ? 0.8 : 0.2), y }, { x: width * (direction === 'next' ? 0.2 : 0.8), y })
  }
  assert.equal(await run('Boolean(document.querySelector(".mobile-workspace-header"))'), false, 'no duplicated section header')
  assert.equal(await run('Boolean(document.querySelector(".mobile-workspace-nav"))'), false, 'no bottom navigation strip')
  assert.equal(await run('document.querySelector(".mobile-conversation-header").getBoundingClientRect().height<64'), true, 'one compact conversation header')
  await nav('Chats')
  await pane('chats')
  assert.equal(await run('document.getElementById("sidebar").getBoundingClientRect().width<innerWidth'), true, 'sidebar leaves a visible conversation backdrop')
  assert.equal(await run('document.getElementById("detail").inert'), true, 'conversation cannot receive input behind the drawer')
  assert.equal(await run('document.getElementById("sidebar").getAttribute("aria-modal")'), 'true')
  assert.equal(await run('Boolean(document.querySelector(\'.mobile-sidebar-footer [aria-label="Limits and usage"], .mobile-sidebar-footer [aria-label="On Limit Reset"]\'))'), false, 'sidebar has no duplicate chat usage controls')
  assert.equal(await run(`(()=>{const sidebar=document.getElementById('sidebar');const controls=[...sidebar.querySelectorAll('button:not(:disabled),input,[tabindex="0"]')].filter(e=>e.getClientRects().length&&!e.closest('[inert]'));controls.at(-1).focus();document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Tab',bubbles:true,cancelable:true}));return document.activeElement===controls[0]})()`), true, 'keyboard focus stays inside the drawer')
  await shot('sidebar')
  const footerActions = await run('[...document.querySelectorAll(".mobile-sidebar-footer__actions button")].map(e=>e.getAttribute("aria-label"))')
  assert.deepEqual(footerActions, ['New chat','New chat without a project','Search conversations','Open settings'])
  assert.equal(await run(`Boolean(document.querySelector('.mobile-sidebar-heading button[aria-label="New chat"]'))`), false)
  const drawerTransition = await run('getComputedStyle(document.querySelector(".mobile-sidebar-backdrop")).transitionDuration')
  assert.match(drawerTransition,/0.18s/,'backdrop and drawer share transition timing')
  const projectHeader = '.chat-list-group--cwd .chat-list-group__header'
  assert.equal(await run('(()=>{const r=document.querySelector(".chat-panel").getBoundingClientRect();return r.left>0&&r.right<innerWidth})()'), true, 'chat pane keeps room for recessed shadow')
  assert.ok(await run('(()=>{const e=document.querySelector(".chat-list-group--cwd .chat-list-group__title");return e.scrollWidth<=e.clientWidth+1 && e.getBoundingClientRect().height>parseFloat(getComputedStyle(e).fontSize)*1.5})()'), 'long project labels grow vertically instead of clipping')
  await hold(projectHeader)
  await waitFor('Boolean(document.querySelector(".mobile-project-actions"))')
  assert.equal(ui.keyboardVisible(), false,'holding project does not open keyboard')
  const sleepLabel = await run('document.querySelector(".mobile-project-actions .ui-button-group > button:last-child")?.getAttribute("aria-label")')
  assert.ok(sleepLabel)
  await tap('.mobile-project-actions .ui-button-group > button:last-child')
  await waitFor('Boolean(document.querySelector(".chat-sleep-panel"))')
  assert.equal(ui.keyboardVisible(), false, 'sleep popup does not autofocus a phone keyboard')
  assert.equal(await run('(()=>{const r=document.querySelector(".chat-sleep-panel").getBoundingClientRect();return r.left>=0&&r.right<=innerWidth+1&&r.top>=0&&r.bottom<=innerHeight+1})()'),true,'nested sleep panel stays within phone viewport')
  await shot('project-sleep-menu')
  await tap('input[aria-label="Sleep duration"]')
  const imeDeadline=Date.now()+10000
  while(Date.now()<imeDeadline&&!ui.keyboardVisible())await delay(100)
  assert.equal(ui.keyboardVisible(), true)
  await delay(300)
  assert.equal(await run('Boolean(document.querySelector(".chat-sleep-panel"))'), true, 'sleep popup survives native keyboard resize')
  await ui.dismissKeyboard()
  adb(['shell','input','keyevent','4'])
  await waitFor('!document.querySelector(".chat-sleep-panel")')
  adb(['shell','input','keyevent','4'])
  await waitFor('!document.querySelector(".mobile-project-actions")')
  await tap('.mobile-sidebar-footer [role="combobox"]')
  await waitFor('Boolean(document.querySelector(\'[role="listbox"]\'))')
  assert.equal(await run('(()=>{const r=document.querySelector(\'[role="listbox"]\').getBoundingClientRect();return r.left>=-1&&r.right<=innerWidth+1&&r.top>=-1&&r.bottom<=innerHeight+1})()'), true, 'sidebar account choices fit the viewport')
  adb(['shell', 'input', 'keyevent', '4'])
  await waitFor('!document.querySelector(\'[role="listbox"]\')')
  await pane('chats')
  await tap('.mobile-sidebar-footer__actions button[aria-label="Search conversations"]')
  await waitFor('Boolean(document.getElementById("chat-search"))')
  await tap('#chat-search')
  const searchImeDeadline = Date.now() + 10000
  while (Date.now() < searchImeDeadline && !ui.keyboardVisible()) await delay(100)
  assert.equal(ui.keyboardVisible(), true, 'sidebar search opens Android keyboard')
  await waitFor('getComputedStyle(document.querySelector(".mobile-sidebar-footer")).display==="none"')
  adb(['shell', 'input', 'text', 'LAN'])
  await waitFor('document.getElementById("chat-search")?.value==="LAN"')
  await shot('sidebar-search')
  await ui.dismissKeyboard()
  adb(['shell', 'input', 'keyevent', '4'])
  await waitFor('!document.querySelector(".chat-home__search-field")')
  await pane('chats')
  await ui.touchPoint(await run('(()=>{const r=document.getElementById("sidebar").getBoundingClientRect();return {x:(r.right+innerWidth)/2,y:innerHeight/2}})()'))
  await pane('conversation')
  assert.equal(await run('document.getElementById("sidebar").inert'), true, 'closed sidebar is not focusable')
  await shot('conversation-first')
  await nav('Chats')
  adb(['shell', 'input', 'keyevent', '4'])
  await pane('conversation')
  await nav('Chats')
  assert.equal(await run(actionsVisible), false, 'chat actions start hidden')
  await tap(`${row} .chat-list-item__main`)
  await pane('conversation')
  assert.equal(await run('Boolean(document.querySelector(".chat-list-item__detail-card"))'), false, 'touch never mounts hover details')
  await run('(()=>{const e=document.createElement("div");e.id="horizontal-swipe-probe";e.style.cssText="position:absolute;inset:20px 12px auto;height:70px;overflow-x:auto;z-index:10";const content=document.createElement("div");content.style.cssText="width:1800px;height:60px";content.textContent="Scrollable code ".repeat(100);e.append(content);document.querySelector(".chat-detail__messages-shell").append(e)})()')
  const nested = await run('(()=>{const r=document.getElementById("horizontal-swipe-probe").getBoundingClientRect();return {left:r.left,width:r.width,y:r.y+r.height/2}})()')
  await swipe({x:nested.left+nested.width*0.8,y:nested.y},{x:nested.left+nested.width*0.2,y:nested.y})
  await pane('conversation')
  assert.ok(await run('document.getElementById("horizontal-swipe-probe").scrollLeft>0'), 'horizontal scrolling stays in its own surface')
  await run('document.getElementById("horizontal-swipe-probe").remove()')
  await horizontal('previous')
  await pane('chats')
  await horizontal('next')
  await pane('conversation')
  await nav('Workspace')
  await pane('workspace')
  await horizontal('previous')
  await pane('chats')
  adb(['shell','input','keyevent','4'])
  await pane('workspace')
  adb(['shell','input','keyevent','4'])
  await pane('conversation')
  await horizontal('previous')
  await pane('chats')
  const point = await run(`(()=>{const r=document.querySelector('${row} .chat-list-item__main').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  await swipe(point, { x: point.x, y: point.y + 85 }, 300)
  await pane('chats')
  assert.equal(await run(actionsVisible), false, 'scrolling cancels hold actions')
  await hold(`${row} .chat-list-item__main`)
  await waitFor(`document.querySelector('${row}')?.dataset.touchActions==='open'`)
  assert.equal(await run(actionsVisible), true, 'hold reveals contextual buttons')
  await pane('chats')
  assert.equal(await run('Boolean(document.querySelector(".chat-list-item__detail-card"))'), false)
  await shot('hold-chat-actions')
  await tap(`${row} [aria-label="Chat menu"]`)
  await waitFor('Boolean(document.querySelector(\'[role="listbox"]\'))')
  adb(['shell', 'input', 'keyevent', '4'])
  await waitFor('!document.querySelector(\'[role="listbox"]\')')
  assert.equal(await run(actionsVisible), true, 'Back closes the menu before its parent context')
  adb(['shell', 'input', 'keyevent', '4'])
  await waitFor(`!document.querySelector('${row}')?.dataset.touchActions`)
  assert.equal(await run(actionsVisible), false, 'Back dismisses the contextual controls')
  await hold(`${row} .chat-list-item__main`)
  await tap(`${row} button[aria-label="Edit chat name"]`)
  await tap(`${row} input[aria-label="Chat name"]`)
  await delay(400)
  await ui.dismissKeyboard()
  adb(['shell', 'input', 'keyevent', '4'])
  await waitFor(`!document.querySelector('${row} input')`)
  adb(['shell', 'input', 'keyevent', '4'])
  await waitFor(`!document.querySelector('${row}')?.dataset.touchActions`)
  await hold(`${row} .chat-list-item__main`)
  await tap(`${row} .chat-list-item__main`)
  await pane('conversation')
  assert.equal(await run(`Boolean(document.querySelector('${row}')?.dataset.touchActions)`), false, 'opening a held chat closes its context')
  await nav('Workspace')
  await tap('.changes-sidebar [aria-label="Sidebar view"] button[aria-label="Git"]')
  await waitFor('Boolean(document.querySelector(".mobile-git-actions"))')
  const measure = () => run('(()=>{const sidebar=document.querySelector(".changes-sidebar").getBoundingClientRect();const body=document.querySelector(".changes-sidebar__body").getBoundingClientRect();return {ratio:body.height/sidebar.height,height:body.height,header:document.querySelector(".changes-sidebar__header").getBoundingClientRect().height,footer:document.querySelector(".mobile-git-actions").getBoundingClientRect().height}})()')
  let geometry = await measure()
  console.log('ANDROID GIT PORTRAIT:', JSON.stringify(geometry))
  assert.ok(geometry.ratio >= 0.7, 'Git content owns at least 70% of the workspace in portrait')
  await shot('git-content-portrait')
  await tap('.mobile-git-actions > button')
  await waitFor('Boolean(document.querySelector(".mobile-git-dialog[open]"))')
  assert.equal((await measure()).height, geometry.height, 'commit sheet does not shrink Git content')
  assert.equal(await run('Boolean(document.querySelector(".mobile-git-dialog .changes-sidebar__commit-row--ai"))'), true, 'existing commit actions remain available in sheet')
  await delay(200)
  await shot('git-commit-sheet')
  adb(['shell', 'input', 'keyevent', '4'])
  await waitFor('!document.querySelector(".mobile-git-dialog[open]")')
  adb(['shell', 'settings', 'put', 'system', 'accelerometer_rotation', '0'])
  adb(['shell', 'settings', 'put', 'system', 'user_rotation', '1'])
  try {
    await waitFor('innerWidth>innerHeight')
    await delay(350)
    geometry = await measure()
    console.log('ANDROID GIT LANDSCAPE:', JSON.stringify(geometry))
    assert.ok(geometry.ratio >= 0.65, 'Git content owns at least 65% of the workspace in landscape')
    await shot('git-content-landscape')
  } finally { adb(['shell', 'settings', 'put', 'system', 'user_rotation', '0']) }
  await waitFor('innerHeight>innerWidth')
  await delay(350)
  await nav('Chats')
  console.log('ANDROID TOUCH LAYOUT PASSED: no hover cards, hold actions, native swipes, scroll cancellation, themed navigation, compact Git and commit sheet')
}
